# ---------------------------------------------------------------- verification helpers
def tt2(f):
    return tuple(f(a, b) for a, b in itertools.product((0, 1), repeat=2))
def tt3(f):
    return tuple(f(a, b, c) for a, b, c in itertools.product((0, 1), repeat=3))
N = lambda x: 1 - x

